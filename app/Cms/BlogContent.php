## Anuradhapura: the first great capital

For roughly 1,400 years, Anuradhapura was the heart of Sri Lankan civilisation. Buddhism reached the island in the 3rd century BCE, and with it came a sapling of the tree under which the Buddha attained enlightenment. That tree, the **Sri Maha Bodhi**, still grows in Anuradhapura and is honoured as one of the oldest living trees planted by humans with a recorded history.

