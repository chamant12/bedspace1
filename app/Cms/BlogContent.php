## Polonnaruwa: the medieval masterpiece

When the capital moved to Polonnaruwa in the 11th century, its kings built a compact city of palaces, audience halls and monasteries beside the vast Parakrama Samudra reservoir. The highlight is the **Gal Vihara**, where four images of the Buddha are carved from a single granite face, including a serene reclining figure some 14 metres long.

## Sigiriya: the fortress in the sky

